import assert from 'node:assert/strict';
import { build } from 'vite';
import { mkdtemp, readFile, writeFile, rm, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { performance } from 'node:perf_hooks';
import process from 'node:process';
import { validatePage } from './prerender-validation.mjs';
import { parseBuildOptions } from './prerender-options.mjs';

const frontend = fileURLToPath(new URL('../', import.meta.url));
let options;
try {
  options = parseBuildOptions(process.argv.slice(2));
} catch (error) {
  console.error(`Prerender: ${error.message}`);
  process.exit(1);
}
const dist = path.resolve(frontend, options.outDir);
const site = 'https://www.energoeffekt-rostov.ru';
const started = performance.now();
// Never load production .env. Client and build renderer use identical defines.
const config = { root: frontend, envDir: false };
const escape = (value) => String(value).replace(/[&<>"']/g, (c) => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
})[c]);

function head(seo) {
  const url = seo.path === null ? null : site + seo.path;
  const tags = [
    ['name', 'description', seo.description], ['name', 'robots', seo.robots],
    ['property', 'og:type', 'website'], ['property', 'og:title', seo.title],
    ['property', 'og:description', seo.description], ['property', 'og:image', site + '/og-image.jpg'],
    ['property', 'og:locale', 'ru_RU'], ['name', 'twitter:card', 'summary_large_image'],
    ['name', 'twitter:title', seo.title], ['name', 'twitter:description', seo.description],
    ['name', 'twitter:image', site + '/og-image.jpg'],
    ...(url ? [['property', 'og:url', url]] : []),
  ];
  return `<title>${escape(seo.title)}</title>\n` + tags.map(([attr, key, value]) =>
    `<meta ${attr}="${key}" content="${escape(value)}">`).join('\n') +
    (url ? `\n<link rel="canonical" href="${escape(url)}">` : '');
}

// Imports render in a Node process without window/storage, and no effects run.
// Reject accidental network use instead of tolerating production requests.
globalThis.fetch = () => { throw new Error('Network is forbidden during prerender'); };
const ssrDir = await mkdtemp(path.join(frontend, 'node_modules/.ee-prerender-'));
const emptyEnvDir = await mkdtemp(path.join(tmpdir(), 'ee-build-env-'));
try {
  await build({ ...config, envDir: emptyEnvDir, build: { outDir: dist } });
  const shell = (await readFile(path.join(dist, 'index.html'), 'utf8'))
    .replace(/<title>[\s\S]*?<\/title>/g, '')
    .replace(/<meta\s+(?:name="(?:description|robots|twitter:[^"]+)"|property="og:[^"]+")[\s\S]*?\/?>/g, '')
    .replace(/<link\s+rel="canonical"[^>]*>/g, '');
  await build({ ...config, envDir: emptyEnvDir, build: {
    ssr: 'src/prerender/entry.jsx', outDir: ssrDir, emptyOutDir: true,
    rollupOptions: { output: { entryFileNames: 'entry.mjs' } },
  } });
  const { render, publicRoutes } = await import(pathToFileURL(path.join(ssrDir, 'entry.mjs')));
  assert.equal(new Set(publicRoutes).size, publicRoutes.length, 'Duplicate route');
  const rows = [];
  for (const route of [...publicRoutes, '/404']) {
    assert.match(route, /^\/(?:[a-z0-9-]+(?:\/[a-z0-9-]+)*)?$/, 'Unsafe route');
    const { html, seo } = render(route);
    assert.equal(seo.path, route === '/404' ? null : route, `SEO route mismatch: ${route}`);
    const document = shell.replace('</head>', `${head(seo)}\n<noscript><style>.faq__panel,.product-details-accordion__panel{grid-template-rows:1fr!important}</style></noscript>\n</head>`)
      .replace('<div id="root"></div>', `<div id="root" data-prerendered="true">${html}</div>`);
    validatePage(document, route, publicRoutes);
    const filename = route === '/' ? 'index.html' : route.slice(1) + '.html';
    await mkdir(path.dirname(path.join(dist, filename)), { recursive: true });
    await writeFile(path.join(dist, filename), document);
    rows.push({ route, file: filename, bytes: Buffer.byteLength(document), title: seo.title, description: seo.description });
  }
  assert.equal(new Set(rows.filter((row) => row.route !== '/404').map((row) => row.title)).size, publicRoutes.length, 'Non-unique titles');
  assert.equal(new Set(rows.filter((row) => row.route !== '/404').map((row) => row.description)).size, publicRoutes.length, 'Non-unique descriptions');
  await writeFile(path.join(dist, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${publicRoutes.map((route) => `  <url><loc>${site}${route}</loc></url>`).join('\n')}\n</urlset>\n`);
  const pattern = publicRoutes.filter((route) => route !== '/').map((route) => route.slice(1)).join('|');
  await writeFile(path.join(dist, 'prerender-routes.conf'), `# Generated by npm run build; do not edit.\nlocation = / { try_files /index.html =404; }\nlocation ~ ^(?<ee_page>/(?:${pattern}))/+$ { return 301 "$ee_page$is_args$args"; }\nlocation ~ ^/(?:${pattern})$ { try_files $uri.html =404; }\nlocation ~ ^/(?:${pattern})\\.html$ { return 404; }\n`);
  // Completeness is checked from disk, including sitemap and every output.
  for (const row of rows) validatePage(await readFile(path.join(dist, row.file), 'utf8'), row.route, publicRoutes);
  await writeFile(path.join(dist, 'prerender-manifest.json'), JSON.stringify({ pages: rows, buildMs: Math.round(performance.now() - started) }, null, 2));
  console.log(`Prerender: ${publicRoutes.length} public pages + 404, validated in ${Math.round(performance.now() - started)}ms`);
} finally {
  await rm(ssrDir, { recursive: true, force: true });
  await rm(emptyEnvDir, { recursive: true, force: true });
}
