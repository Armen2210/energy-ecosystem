"""Generate the ordered gallery with Pillow (EXIF-aware WebP, never upscale).
Run from any directory: python scripts/prepare-about-gallery.py. Source files stay intact.
"""
from pathlib import Path
import json
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'src/assets/about/gallery-source'
OUTPUT = ROOT / 'src/assets/about/gallery'
ALTS = [
    'Сотрудники за рабочими столами в светлом офисе',
    'Рабочее место с инженерными чертежами на двух мониторах',
    'Специалист за компьютером с трёхмерной моделью оборудования',
    'Насосная установка на раме в производственном цехе',
    'Трубная обвязка и шкаф управления на раме установки',
    'Трубопроводы с фланцами и запорной арматурой',
    'Узел трубопроводов и измерительных приборов на раме',
    'Коллекторы с красной запорной арматурой',
    'Газопровод жёлтого цвета рядом с котельным оборудованием',
    'Насосы и вертикальные трубопроводы внутри установки',
    'Инженерное оборудование в модульном блоке на открытой площадке',
    'Открытый модульный блок на автомобильном полуприцепе',
    'Сборочные участки и оборудование в производственном цехе',
    'Шкаф управления и трубная обвязка установки в цехе',
    'Производственный цех с оборудованием на сборке',
    'Стальной трубопровод с крупными фланцевыми соединениями',
    'Предупреждающая табличка на производственном участке',
    'Латунные соединительные детали перед коробками комплектующих',
    'Клеммы и проводка внутри электрического шкафа',
    'Открытый шкаф управления на раме инженерной установки',
    'Кружки и контейнер с мелкими деталями на рабочем столе',
    'Инструментальная панель с отвёртками и рулеткой',
    'Защитная каска и очки на полке',
    'Табличка «Начальник цеха» на двери',
    'Сборка электрической панели рядом с красной арматурой',
    'Настенный ящик с надписью «Я ящик для хороших идей!»',
    'Табличка «Энергоэффект» на кирпичной стене',
]
files = list(SOURCE.iterdir())
if any(not p.is_file() or not p.stem.isdigit() for p in files):
    raise ValueError('Ambiguous/non-numeric gallery filename')
numbers = [int(p.stem) for p in files]
missing = sorted(set(range(1, 28)) - set(numbers))
duplicates = sorted(n for n in set(numbers) if numbers.count(n) > 1)
if len(files) != 27 or missing or duplicates or set(numbers) != set(range(1, 28)):
    raise ValueError(f'Gallery: count={len(files)}, missing={missing}, duplicates={duplicates}, numbers={sorted(numbers)}')
OUTPUT.mkdir(exist_ok=True)
rows = []
imports = []
entries = []
for path in sorted(files, key=lambda p: int(p.stem)):
    number = int(path.stem)
    with Image.open(path) as source:
        image = ImageOps.exif_transpose(source).convert('RGB')
    variants = []
    for width in sorted({min(image.width, width) for width in (360, 720, 1080)}):
        height = round(image.height * width / image.width)
        name = f'{number:02d}-{width}.webp'
        image.resize((width, height), Image.Resampling.LANCZOS).save(OUTPUT / name, 'WEBP', quality=80, method=6)
        variants.append({'file': name, 'width': width, 'height': height, 'bytes': (OUTPUT / name).stat().st_size})
        imports.append(f'import image{number}w{width} from "../assets/about/gallery/{name}";')
    primary = next(v for v in variants if v['width'] == min(720, image.width))
    row = {'number': number, 'source': path.name, 'sourceBytes': path.stat().st_size,
           'width': image.width, 'height': image.height, 'alt': ALTS[number - 1], 'variants': variants}
    rows.append(row)
    srcset = ', '.join('${image' + str(number) + 'w' + str(v['width']) + '} ' + str(v['width']) + 'w' for v in variants)
    entries.append('  {' + f'number: {number}, width: {image.width}, height: {image.height}, alt: {json.dumps(ALTS[number - 1], ensure_ascii=False)}, src: image{number}w{primary["width"]}, srcSet: `{srcset}`' + '},')
(OUTPUT / 'manifest.json').write_text(json.dumps(rows, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
(ROOT / 'src/data/aboutGallery.js').write_text('// Generated by scripts/prepare-about-gallery.py; ordered source manifest with descriptive alt.\n' + '\n'.join(imports) + '\nexport const aboutGallery = [\n' + '\n'.join(entries) + '\n];\n', encoding='utf-8')
print(json.dumps({'count': len(rows), 'sourceBytes': sum(r['sourceBytes'] for r in rows), 'derivativeBytes': sum(v['bytes'] for r in rows for v in r['variants']), 'variants': sum(len(r['variants']) for r in rows)}, indent=2))
