function ProductPage() {
  const { slug } = useParams();
  const product = products.find((item) => item.slug === slug);
  const productFaq = productFaqBySlug[slug] || [];

  if (!product) {
    return (
      <main>


        <section className="section">
          <div className="container">
            <SectionHeader
              eyebrow="Продукция"
              title="Направление не найдено"
              description="Проверьте адрес страницы или вернитесь к списку продуктовых направлений."
            />
          </div>
        </section>
      </main>
    );
  }



  return (
    <main>
      <Seo
          title={`${product.title} — производство и инженерное решение | Энергоэффект`}
          description={`${product.title}: подбор и производство под требования объекта, проектные условия, эксплуатацию и сроки. Можно отправить ТЗ, проект или спецификацию для первичной оценки.`}
          path={`/solutions/${product.slug}`}
      />

         <section className="section section--entity-page">
          <div className="container">
            <EntitySwitcher
              items={products}
              currentSlug={product.slug}
              basePath="/solutions"
              variant="products"
              ariaLabel="Переключатель продуктовых направлений"
            />

        {/* =========================================================
            PRODUCT HERO / ВЕРХ ПРОДУКТОВОЙ СТРАНИЦЫ
            Если у продукта задан heroImage, показываем продуктовый
            визуал и отдельный H1. Для остальных продуктов временно
            сохраняем старый SectionHeader, чтобы ничего не сломать.
            ========================================================= */}

        {product.heroImage ? (
          <section className="product-hero" aria-labelledby="product-hero-title">
            <div className="product-hero__visual">
              <img src={product.heroImage} alt={product.heroImageAlt} />
            </div>

            <div className="product-hero__content">
              <h1 id="product-hero-title">
                {product.heroTitle || product.title}
              </h1>

              {product.heroSubtitle && (
                <p className="product-hero__subtitle">
                  {product.heroSubtitle}
                </p>
              )}
            </div>
          </section>
        ) : (
          <SectionHeader
            title={product.title}
            description={product.description}
          />
        )}

          {product.aiSummary && (
              <AiSummary
                title={product.aiSummary.title}
                lead={product.aiSummary.lead}
                items={product.aiSummary.items || []}
              />
          )}

          {product.detailSections?.length > 0 && (
              <ProductDetailsAccordion
                  sections={product.detailSections}
                  stateKey={`product-details-${product.slug}`}
              />
          )}



          {/* =========================================================
                PRODUCT FAQ / ВОПРОСЫ ПО ПРОДУКТУ
                Короткий FAQ усиливает страницу для SEO, AEO/GEO
                и помогает пользователю быстрее понять условия заявки.
                ========================================================= */}

          <div className="section-block">
              <SectionHeader
                eyebrow="Вопросы"
                title={`Частые вопросы: ${product.shortTitle}`}
                description="Короткие ответы по расчёту, исходным данным и подготовке заявки."
              />

              <FAQ items={productFaq} stateKey={`product-${product.slug}`} />
          </div>

        </div>
      </section>

      <section id="lead-form" className="section section--contact">
        <div className="container contact-grid">
          <div>
            <SectionHeader
              eyebrow="Заявка"
              title={`Обсудить направление: ${product.shortTitle}`}
              description="Оставьте контакты и приложите файл, если есть техническое задание, проект или спецификация."
            />
          </div>

          <LeadForm
              products={products}
              services={services}
              initialTopic={product.title}
          />
        </div>
      </section>
    </main>
  );
}

export default ProductPage;