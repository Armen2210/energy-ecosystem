function ServicePage() {
  const { slug } = useParams();
  const service = services.find((item) => item.slug === slug);
  const serviceFaq = serviceFaqBySlug[slug] || [];

  if (!service) {
    return (
      <main>
        <section className="section">
          <div className="container">
            <SectionHeader
              eyebrow="Услуги"
              title="Услуга не найдена"
              description="Проверьте адрес страницы или вернитесь к списку услуг компании."
            />
          </div>
        </section>
      </main>
    );
  }



  return (
    <main>
      <Seo
          title={`${service.title} — инженерные услуги | Энергоэффект`}
          description={`${service.title}: работы для инженерных объектов с учётом требований проекта, условий объекта, эксплуатации и сроков. Можно отправить ТЗ, проект или спецификацию для первичной оценки.`}
          path={`/services/${service.slug}`}
      />

          <section className="section section--entity-page">
           <div className="container">
            <EntitySwitcher
              items={services}
              currentSlug={service.slug}
              basePath="/services"
              variant="services"
              ariaLabel="Переключатель услуг компании"
            />

            {service.heroImage ? (
              <section
                className={`product-hero ${
                  service.heroImageMode ? `product-hero--${service.heroImageMode}` : ""
                }`}
                aria-labelledby="service-hero-title"
              >
                <div className="product-hero__visual">
                  <img
                    src={service.heroImage}
                    alt={service.heroImageAlt || service.title}
                  />
                </div>

                <div className="product-hero__content">
                  <h1 id="service-hero-title">
                    {service.heroTitle || service.title}
                  </h1>

                  {(service.heroSubtitle || service.description) && (
                    <p className="product-hero__subtitle">
                      {service.heroSubtitle || service.description}
                    </p>
                  )}
                </div>
              </section>
            ) : (
              <SectionHeader
                title={service.title}
                description={service.description}
              />
            )}

          <AiSummary
              title={service.aiSummary.title}
              lead={service.aiSummary.lead}
              items={service.aiSummary.items}
          />

          {service.detailSections?.length > 0 && (
              <ProductDetailsAccordion
                sections={service.detailSections}
                stateKey={`service-details-${service.slug}`}
              />
          )}

          {/* =========================================================
                SERVICE FAQ / ВОПРОСЫ ПО УСЛУГЕ
                Короткий FAQ усиливает страницу для SEO, AEO/GEO
                и помогает пользователю быстрее понять состав работ.
                ========================================================= */}

          <div className="section-block">
              <h2 className="visually-hidden">
                {`Частые вопросы: ${service.shortTitle}`}
              </h2>

              <SectionHeader
                eyebrow={`Частые вопросы: ${service.shortTitle}`}
              />

              <FAQ items={serviceFaq} stateKey={`service-${service.slug}`} />
          </div>

        </div>
      </section>

      <section id="lead-form" className="section section--contact">
        <div className="container contact-grid">
          <div>
              <h2 className="visually-hidden">
                {`Обсудить услугу: ${service.shortTitle}`}
              </h2>

              <SectionHeader
                eyebrow={`Обсудить услугу: ${service.shortTitle}`}
                description="Оставьте контакты и приложите файл, если есть техническое задание, проект или спецификация."
              />
          </div>

          <LeadForm
              products={products}
              services={services}
              initialTopic={service.title}
          />
        </div>
      </section>
    </main>
  );
}

export default ServicePage;